// ==========================================
// AUDIO
// ==========================================

const musicAudio = new Audio();

const ambientAudio = new Audio(
    "https://codeskulptor-demos.commondatastorage.googleapis.com/ricochet_game/ricochet_track.mp3"
);

ambientAudio.loop = true;


// ==========================================
// CURRENT TRACK
// ==========================================

let currentTrackIndex = 0;


// ==========================================
// DOM ELEMENTS
// ==========================================

const playBtn =
    document.getElementById("play-btn");

const nextBtn =
    document.getElementById("next-btn");

const prevBtn =
    document.getElementById("prev-btn");

const trackTitle =
    document.getElementById("track-title");

const trackArtist =
    document.getElementById("track-artist");

const musicVol =
    document.getElementById("music-vol");


const progressBar =
    document.getElementById("progress-bar");

const currentTime =
    document.getElementById("current-time");

const duration =
    document.getElementById("duration");


// ==========================================
// LOAD SONG
// ==========================================

function loadSong(index) {

    currentTrackIndex = index;

    const song =
        playlist[currentTrackIndex];

    musicAudio.src = song.src;

    trackTitle.innerText =
        song.title;

    trackArtist.innerText =
        song.artist;

    progressBar.value = 0;

    currentTime.innerText = "0:00";

}


// ==========================================
// PLAY
// ==========================================

function playSong() {

    musicAudio.volume =
        Number(musicVol.value);

    
    musicAudio.play();

    ambientAudio.play().catch(() => {});

    playBtn.innerText = "⏸";

}


// ==========================================
// PAUSE
// ==========================================

function pauseSong() {

    musicAudio.pause();

    ambientAudio.pause();

    playBtn.innerText = "▶";

}


// ==========================================
// PLAY / PAUSE
// ==========================================

playBtn.addEventListener("click", () => {

    if (musicAudio.paused) {

        playSong();

    } else {

        pauseSong();

    }

});


// ==========================================
// NEXT
// ==========================================

nextBtn.addEventListener("click", () => {

    currentTrackIndex++;

    if (
        currentTrackIndex >=
        playlist.length
    ) {

        currentTrackIndex = 0;

    }

    loadSong(currentTrackIndex);

    playSong();

});


// ==========================================
// PREVIOUS
// ==========================================

prevBtn.addEventListener("click", () => {

    currentTrackIndex--;

    if (currentTrackIndex < 0) {

        currentTrackIndex =
            playlist.length - 1;

    }

    loadSong(currentTrackIndex);

    playSong();

});


// ==========================================
// AUTOMATIC NEXT SONG
// ==========================================

musicAudio.addEventListener("ended", () => {

    currentTrackIndex++;

    if (
        currentTrackIndex >=
        playlist.length
    ) {

        currentTrackIndex = 0;

    }

    loadSong(currentTrackIndex);

    playSong();

});


// ==========================================
// MUSIC VOLUME
// ==========================================

musicVol.addEventListener("input", (e) => {

    musicAudio.volume =
        Number(e.target.value);

});



// ==========================================
// PROGRESS UPDATE
// ==========================================

musicAudio.addEventListener(
    "timeupdate",
    () => {

        if (!musicAudio.duration) return;

        const percentage =
            (musicAudio.currentTime /
            musicAudio.duration) * 100;

        progressBar.value =
            percentage;

        currentTime.innerText =
            formatTime(
                musicAudio.currentTime
            );

    }
);


// ==========================================
// DURATION
// ==========================================

musicAudio.addEventListener(
    "loadedmetadata",
    () => {

        duration.innerText =
            formatTime(
                musicAudio.duration
            );

    }
);


// ==========================================
// SEEK
// ==========================================

progressBar.addEventListener(
    "input",
    () => {

        if (!musicAudio.duration)
            return;

        const newTime =
            (progressBar.value / 100)
            * musicAudio.duration;

        musicAudio.currentTime =
            newTime;

    }
);


// ==========================================
// FORMAT TIME
// ==========================================

function formatTime(seconds) {

    if (!seconds || isNaN(seconds)) {
        return "0:00";
    }

    const minutes =
        Math.floor(seconds / 60);

    const remainingSeconds =
        Math.floor(seconds % 60);

    return (
        minutes +
        ":" +
        String(remainingSeconds).padStart(2, "0")
    );

}


